import React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean }
>(({ className, hoverEffect = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "bg-white rounded-xl border border-slate-200/80 shadow-xs overflow-hidden transition-all duration-150",
      hoverEffect && "hover:shadow-md hover:border-slate-300 transition-shadow",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

